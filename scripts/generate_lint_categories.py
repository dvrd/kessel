"""Regenerate src/lint_category_data.odin.

A rule takes part in oxlint category selection (`categories` in .oxlintrc.json)
only when it has a same-name rule in the pinned oxlint inventory and its
recorded agreement with that rule is complete: every upstream fixture that
could be compared reports the same diagnostic ranges. A rule that is known to
differ is never switched on by a category, only by its own name.

Usage: python3 scripts/generate_lint_categories.py
"""

import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
PLUGINS = {3: "typescript", 5: "oxc", 6: "unicorn"}
REACT = {"L4107_RulesOfHooks", "L4108_ExhaustiveDeps"}


def main():
    source = (ROOT / "src/lint.odin").read_text()
    inventory = json.loads((ROOT / "tests/baselines/oxlint_rules.json").read_text())
    parity = json.loads((ROOT / "tests/lint/upstream_parity.json").read_text())
    assert inventory["version"] == parity["oxlint"]
    categories = {rule["id"]: rule["category"] for rule in inventory["rules"]}
    names = dict(re.findall(r'case \.(L\d+_\w+):\s*return LintRuleInfo\{\s*name\s*=\s*"([^"]+)"', source))
    rows = []
    for member in sorted(names):
        # The React Hooks rules follow the `react` plugin switch in lint_config.odin.
        if member in REACT:
            continue
        code = int(member[1:5])
        plugin = PLUGINS.get(code // 1000, "eslint")
        rule_id = plugin + "/" + names[member]
        record = parity["rules"].get(rule_id)
        if rule_id not in categories or record is None:
            continue
        complete = record["fixtures"] > 0 and record["matched"] == record["fixtures"]
        if complete:
            rows.append((member, categories[rule_id]))
    assert rows, "No rule has complete recorded agreement"
    lines = [
        "package kessel",
        "",
        "// Generated by scripts/generate_lint_categories.py from the oxlint " + inventory["version"] + " inventory",
        "// and tests/lint/upstream_parity.json. Do not edit by hand.",
        "//",
        "// Only rules whose recorded agreement with oxlint is complete are listed, so a",
        "// category never enables a rule that is known to report different ranges.",
        "LintCategory :: enum u8 { None, Correctness, Suspicious, Pedantic, Perf, Style, Restriction, Nursery }",
        "",
        "LINT_CATEGORY_RULE_COUNT :: " + str(len(rows)),
        "",
        "lint_rule_category :: proc(rule: LintRule) -> LintCategory {",
        "\t#partial switch rule {",
    ]
    for category in ["correctness", "suspicious", "pedantic", "perf", "style", "restriction", "nursery"]:
        members = [member for member, name in rows if name == category]
        for start in range(0, len(members), 3):
            chunk = ", ".join("." + member for member in members[start:start + 3])
            last = start + 3 >= len(members)
            lines.append("\t" + ("case " if start == 0 else "     ") + chunk + (":" if last else ","))
        if members:
            lines.append("\t\treturn ." + category.capitalize())
    lines += ["\t}", "\treturn .None", "}", ""]
    (ROOT / "src/lint_category_data.odin").write_text("\n".join(lines))
    print("Recorded categories for " + str(len(rows)) + " rules")


main()
