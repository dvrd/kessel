"""Regenerate Kessel's environment names from the crate pinned by the Oxc oracle.

Pass the javascript-globals-1.5.0.crate archive and its upstream LICENSE.
The embedded notice accompanies the data in each native binary.
"""

import hashlib
from pathlib import Path
import re
import sys
import tarfile


def main(archive, license_path):
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    if digest != "c90bade29de7a160120c2630c6e2e020684e3948e93e34618a5f6c9a63dd1329":
        raise ValueError("Expected javascript-globals 1.5.0 from the Oxc Cargo.lock")
    notice = license_path.read_text().strip()
    if "Copyright (c) 2024-present VoidZero Inc. & Contributors" not in notice:
        raise ValueError("Expected the javascript-globals MIT license")
    with tarfile.open(archive) as crate:
        source = crate.extractfile("javascript-globals-1.5.0/src/lib.rs").read().decode()
    environments = dict(re.findall(r'\("([^"]+)", &(GLOBALS_\w+)\)', source))
    tables = dict(re.findall(r'pub static (GLOBALS_\w+):[^;]+?entries: &\[(.*?)\],\s*};', source, re.S))
    names = ["builtin", *sorted(environments.keys() - {"builtin"})]
    assert len(names) == 43 and len(tables) == len(names)
    masks = {}
    for index, environment in enumerate(names):
        entries = re.findall(r'\("([^"]+)", (true|false)\)', tables[environments[environment]])
        assert entries
        for name, writable in entries:
            assert name.isascii() and not any(c.isspace() for c in name)
            present, mutable = masks.get(name, (0, 0))
            bit = 1 << index
            masks[name] = (present | bit, mutable | bit if writable == "true" else mutable)
    groups = {}
    for name, flags in sorted(masks.items()):
        groups.setdefault(flags, []).append(name)
    assert len(masks) == 1600
    lines = [notice, "", "[environments]", " ".join(names), "[globals]"]
    for (present, writable), members in sorted(groups.items()):
        lines.append(f"{present:x} {writable:x} {' '.join(members)}")
    data = "\n".join(lines)
    assert "`" not in data
    target = Path(__file__).resolve().parents[1] / "src/lint_environment_data.odin"
    target.write_text("package kessel\n\n// Generated by scripts/generate_lint_environments.py"
                      " from javascript-globals 1.5.0.\n"
                      + f"LINT_ENVIRONMENT_DATA :: `{data}\n`\n")


if __name__ == "__main__":
    main(*(Path(arg) for arg in sys.argv[1:]))
