// Compare which declaration each identifier reads or writes, independently of its local spelling.
use oxc_allocator::Allocator;
use oxc_parser::{ParseOptions, Parser};
use oxc_semantic::SemanticBuilder;
use oxc_span::SourceType;
use std::{env, fs, path::Path, process::ExitCode};

#[derive(Debug, PartialEq)]
enum Binding {
    Declaration {
        flags: u32,
        scope: usize,
        public_name: Option<String>,
    },
    Reference {
        declaration: usize,
        flags: u8,
    },
    Global {
        name: String,
        flags: u8,
    },
}

fn bindings(path: &Path, source_type: SourceType) -> Result<Vec<(u32, Binding)>, String> {
    let text = fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let arena = Allocator::default();
    // Parentheses around a member receiver have no effect on which binding is read.
    let parsed = Parser::new(&arena, &text, source_type)
        .with_options(ParseOptions {
            preserve_parens: false,
            ..Default::default()
        })
        .parse();
    if !parsed.errors.is_empty() {
        return Err(format!("{}: {:?}", path.display(), parsed.errors));
    }
    // Only a file with import or export syntax has a private top level.
    let module = parsed.module_record.has_module_syntax;
    let analysis = SemanticBuilder::new().build(&parsed.program).semantic;
    let scopes = analysis.scoping();
    let mut symbols: Vec<_> = scopes.symbol_ids().collect();
    symbols.sort_by_key(|&id| scopes.symbol_span(id).start);

    let mut uses = Vec::new();
    for (declaration, id) in symbols.into_iter().enumerate() {
        let scope = scopes.symbol_scope_id(id);
        // A script's top-level names are visible to other scripts. A module's are
        // private, so renaming them is allowed; its export list is compared by
        // the caller instead.
        let public_name = (scope == scopes.root_scope_id() && !module)
            .then(|| scopes.symbol_name(id).to_owned());
        uses.push((
            scopes.symbol_span(id).start,
            Binding::Declaration {
                flags: scopes.symbol_flags(id).bits(),
                scope: scope.index(),
                public_name,
            },
        ));
        for reference in analysis.symbol_references(id) {
            uses.push((
                analysis.reference_span(reference).start,
                Binding::Reference {
                    declaration,
                    flags: reference.flags().bits(),
                },
            ));
        }
    }
    for (name, ids) in scopes.root_unresolved_references() {
        for &id in ids {
            let reference = scopes.get_reference(id);
            uses.push((
                analysis.reference_span(reference).start,
                Binding::Global {
                    name: name.to_string(),
                    flags: reference.flags().bits(),
                },
            ));
        }
    }
    uses.sort_by_key(|(offset, _)| *offset);
    Ok(uses)
}

fn compare(original: &Path, generated: &Path) -> Result<usize, String> {
    let source_type = SourceType::from_path(original).map_err(|e| e.to_string())?;
    let before = bindings(original, source_type)?;
    let after = bindings(generated, source_type)?;
    if before.len() != after.len() {
        return Err(format!(
            "Binding count changed from {} to {}",
            before.len(),
            after.len()
        ));
    }
    for ((left_offset, left), (right_offset, right)) in before.iter().zip(&after) {
        if left != right {
            return Err(format!(
                "Original byte {left_offset}: {left:?}, generated byte {right_offset}: {right:?}"
            ));
        }
    }
    Ok(before.len())
}

fn main() -> ExitCode {
    let args: Vec<_> = env::args_os().skip(1).collect();
    if args.len() != 2 {
        eprintln!("Usage: minify_bindings <original file> <generated file>");
        return ExitCode::FAILURE;
    }
    match compare(Path::new(&args[0]), Path::new(&args[1])) {
        Ok(count) => {
            println!("{count}");
            ExitCode::SUCCESS
        }
        Err(message) => {
            eprintln!("{}: {message}", Path::new(&args[0]).display());
            ExitCode::FAILURE
        }
    }
}
